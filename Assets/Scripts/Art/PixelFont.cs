        public static void ResetCache()
        {
            _sprites = null;
            _glyphs = null;
            _atlas = null;
        }

        public static string[] Rows(char c)
        {
            if (_glyphs == null) _glyphs = Build();
            if (_glyphs.TryGetValue(c, out var r)) return r;
            if (_glyphs.TryGetValue(char.ToUpperInvariant(c), out var u)) return u;
            return _glyphs['?'];
        }

        public static bool Supports(char c)
        {
            if (_glyphs == null) _glyphs = Build();
            return _glyphs.ContainsKey(c) || _glyphs.ContainsKey(char.ToUpperInvariant(c));
        }

        public static Sprite Glyph(char c)
        {
            EnsureAtlas();
            char key = char.ToUpperInvariant(c);
            if (!_glyphs.ContainsKey(key)) key = '?';
            if (_sprites.TryGetValue(key, out var sp)) return sp;

            var rows = _glyphs[key];
            var p = new Px(GW, GH, new Color32(255, 255, 255, 0));
            for (int r = 0; r < GH; r++)
                for (int i = 0; i < GW; i++)
                    if (rows[r][i] == '1') p.Set(i, GH - 1 - r, new Color32(255, 255, 255, 255));

            sp = p.ToSprite("glyph_" + key, PPU, Vector2.zero);
            _sprites[key] = sp;
            return sp;
        }

        static void EnsureAtlas()
        {
            if (_sprites != null) return;
            _glyphs = Build();
            _sprites = new Dictionary<char, Sprite>();
        }
